export interface CareerRank {
  title: string;
  minXp: number;
}

export const CAREER_RANKS: CareerRank[] = [
  { title: 'Magang Apotek', minXp: 0 },
  { title: 'Asisten Apoteker Muda', minXp: 150 },
  { title: 'Apoteker Muda Klinik', minXp: 350 },
  { title: 'Apoteker Klinis Senior', minXp: 600 },
  { title: 'Master Tabib Kalarma', minXp: 900 },
];

export function getRankForXp(xp: number): { current: CareerRank; next: CareerRank | null } {
  let current = CAREER_RANKS[0];
  let next: CareerRank | null = CAREER_RANKS[1];
  for (let i = 0; i < CAREER_RANKS.length; i++) {
    if (xp >= CAREER_RANKS[i].minXp) {
      current = CAREER_RANKS[i];
      next = CAREER_RANKS[i + 1] ?? null;
    }
  }
  return { current, next };
}
